#!/usr/bin/env python3
"""Regenerate and validate the paper's models, independently of the paper folder.

Examples (from any working directory):
  python scripts/generate_models.py
  python scripts/generate_models.py --printable --preview
  python scripts/generate_models.py --check --printable
  python scripts/generate_models.py --model '*g4*' --output /path/to/output
"""
import argparse
from fnmatch import fnmatchcase
import hashlib
import json
from pathlib import Path

import numpy as np

from embedded_models import build_models as embedded_models
from immersed_models import build_models as immersed_models
from singular_models import build_models as singular_models
from mesh_geometry import (prepare_model, read_stl, stl_surface, triangle_defects,
                           triangle_mesh_report, write_bytes_atomic, write_obj, write_stl)

ROOT = Path(__file__).resolve().parents[1]


def json_value(value):
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    raise TypeError(type(value).__name__)


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    write_bytes_atomic(path, (json.dumps(value, indent=2, ensure_ascii=False, default=json_value) + "\n").encode("utf-8"))


def verify_export(path, vertices, triangles):
    """Reload actual STL bytes and verify welding and exact float32 geometry."""
    rv, rt = read_stl(path)
    expected_points = vertices[triangles].astype(np.float32).astype(float)
    if not np.array_equal(rv[rt], expected_points):
        raise ValueError(f"STL differs from regenerated geometry: {path}")
    report = triangle_mesh_report(rv, rt)
    if any(report[k] for k in ("boundary_edges", "nonmanifold_edges", "degenerate_triangles", "duplicate_triangles")):
        raise ValueError(f"Invalid closed STL surface: {path}: {report}")
    # Vertex order is changed by STL welding, so compare positions by keys.
    defects = triangle_defects(rv, rt)
    exact_defects = triangle_defects(vertices, triangles)
    lookup = {tuple(p): d for p,d in zip(vertices.astype(np.float32).astype(float), exact_defects)}
    error = max(abs(d-lookup[tuple(p)]) for p,d in zip(rv, defects))
    if error > 5e-5:
        raise ValueError(f"STL rounding changed defects by {error:g} radians")
    report["max_float32_defect_error"] = float(error)
    report["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    return report


def render_preview(models, output):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
    wanted = [
        "embedded_orientable_g1_v9_flat_torus", "embedded_orientable_g3_v24_windows",
        "embedded_orientable_g6_v35_central_handle", "embedded_orientable_g8_v48_shared_windows",
        "immersed_nonorientable_g1_v9_projective_plane", "immersed_nonorientable_g2_v15_klein_bottle",
        "immersed_nonorientable_g3_v27_mobius_bands", "singular_nonorientable_g3_v15_antiprism",
        "singular_nonorientable_g4_v12_cubohemioctahedron",
    ]
    chosen = [m for name in wanted for m in models if m["name"] == name]
    if not chosen:
        chosen = models[:9]
    fig = plt.figure(figsize=(13.5, 4.1*((len(chosen)+2)//3)), facecolor="#f7f9fc")
    palette = ["#5e9db2", "#edc783", "#9cadcd", "#99c7bf"]
    for i,m in enumerate(chosen):
        ax = fig.add_subplot((len(chosen)+2)//3, 3, i+1, projection="3d")
        v = m["vertices"]
        triangles = m["triangles"]
        colors = [palette[j % len(palette)] for j in range(len(triangles))]
        ax.add_collection3d(Poly3DCollection(v[triangles], facecolors=colors, edgecolors="#344c5f", linewidths=.22, alpha=.85))
        center, span = (v.max(axis=0)+v.min(axis=0))/2, np.ptp(v,axis=0).max()
        for set_limits,c in zip((ax.set_xlim,ax.set_ylim,ax.set_zlim),center):
            set_limits(c-span*.54,c+span*.54)
        ax.set_box_aspect([1,1,1])
        ax.view_init(elev=26,azim=-57)
        ax.set_axis_off()
        category=m["name"].split("_")[0].capitalize()
        label=m["name"].split(f"_v{len(v)}_",1)[-1].replace("_"," ").capitalize()
        ax.set_title(f"{label}\n{category} | genus {m['genus']} | {len(v)} vertices",fontsize=11,color="#233d50",pad=1)
    fig.suptitle("Polyhedra of Constant Gaussian Curvature",fontsize=20,color="#233d50",y=.992)
    fig.subplots_adjust(left=.01,right=.99,bottom=.01,top=.94,wspace=.01,hspace=.1)
    output.parent.mkdir(parents=True,exist_ok=True)
    fig.savefig(output,dpi=160,facecolor=fig.get_facecolor())
    plt.close(fig)


def write_catalog(root, models, reports):
    lines = ["# Model catalog", "", "Generated by `python scripts/generate_models.py`. `V` counts the original paper vertices, before STL subdivision or print thickening.", "",
             "| Model | Genus | V | Source |", "|---|---:|---:|---|"]
    for m in models:
        name=m["name"]
        source=m["source"]
        lines.append(f"| [{name}](../stl/{name}.stl) | {m['genus']} | {len(m['vertices'])} | {source} |")
    lines += ["", "The matching JSON files contain the original polygon incidences and double-precision coordinates; OBJ files in `../obj/` preserve those polygons.", "",
              "All source surfaces are closed abstract surfaces. Only the embedded family bounds a solid directly. Immersed and singular models retain the paper's intersections. Use the matching `../3dprint/` STL for a thickened solid.", "",
              "Some singular STL exports add flat subdivision vertices to distinguish parallel abstract diagonals. These points have zero defect and are not included in V. See `validation.json` for the source and exported counts.", ""]
    write_bytes_atomic(root/"models"/"README.md", "\n".join(lines).encode("utf-8"))
    write_json(root/"models"/"validation.json", {"models":reports,
               "checks":"Polygon incidences, single-cycle vertex links, orientability, Euler characteristic, planarity, simple polygons, intrinsic defects, triangulation areas, exported STL closure and float32 rounding.",
               "embeddedness":"The analytic constructions follow the paper's embedding proofs; see scripts/check_embedded_intersections.py for the supplementary numerical intersection check when present.",
               "stl_units":"Paper coordinate units. The separate 3dprint STL files use millimetres."})


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output",type=Path,default=ROOT,help="Output repository/directory (default: this repository)")
    parser.add_argument("--model",action="append",default=[],help="Model name or glob; repeat to select multiple")
    parser.add_argument("--list",action="store_true",help="List available names")
    parser.add_argument("--check",action="store_true",help="Validate existing files against rebuilt geometry without rewriting")
    parser.add_argument("--printable",action="store_true",help="Also produce/check closed solid STL files in 3dprint/")
    parser.add_argument("--size-mm",type=float,default=80.0,help="Maximum source dimension for print copies")
    parser.add_argument("--thickness-mm",type=float,default=2.4,help="Full shell thickness of intersecting surfaces")
    parser.add_argument("--pitch-mm",type=float,default=.8,help="Grid spacing for thickened print aids")
    parser.add_argument("--preview",action="store_true",help="Render images/model_overview.png")
    args=parser.parse_args(argv)
    if args.size_mm<=0 or not np.isfinite(args.size_mm):
        parser.error("--size-mm must be finite and positive")
    models=embedded_models()+immersed_models()+singular_models()
    if args.model:
        models=[m for m in models if any(fnmatchcase(m["name"],p) for p in args.model)]
    if not models:
        parser.error("No models matched --model")
    if args.list:
        print("\n".join(m["name"] for m in models))
        return
    reports, prepared = [], []
    for raw in models:
        model, report=prepare_model(raw)
        name=model["name"]
        vertices,triangles=stl_surface(model)
        path=args.output/"stl"/(name+".stl")
        metadata={k:v for k,v in model.items() if k!="triangles"}
        metadata["representation"]="Original paper polygon presentation; zero-based face indices; paper coordinate units"
        if not args.check:
            write_stl(path,vertices,triangles,name)
            write_obj(args.output/"obj"/(name+".obj"),model)
            write_json(args.output/"models"/(name+".json"),metadata)
        else:
            stored=json.loads((args.output/"models"/(name+".json")).read_text(encoding="utf-8"))
            if stored != json.loads(json.dumps(metadata,default=json_value)):
                raise ValueError(f"Stored polygon model differs: {name}")
        report["stl"]=verify_export(path,vertices,triangles)
        report["stl"]["added_flat_vertices"]=len(vertices)-len(model["vertices"])
        if args.printable:
            from printable_models import make_printable, _verify_closed
            print_path=args.output/"3dprint"/(name+".stl")
            report_path=args.output/"3dprint"/(name+".json")
            if not args.check:
                if name.startswith("embedded_"):
                    scale=args.size_mm/np.ptp(model["vertices"],axis=0).max()
                    pv=(model["vertices"]-(model["vertices"].min(axis=0)+model["vertices"].max(axis=0))/2)*scale
                    pt=model["triangles"]
                    pr={"method":"Uniformly scaled embedded solid boundary; no thickening", "size_mm":args.size_mm,"scale":scale}
                else:
                    pv,pt,pr=make_printable(model["vertices"],model["triangles"],args.size_mm,args.thickness_mm,args.pitch_mm)
                write_stl(print_path,pv,pt,"print_"+name)
            else:
                pr=json.loads(report_path.read_text(encoding="utf-8"))
                if pr["source_model"] != name or pr["source_stl_sha256"] != report["stl"]["sha256"]:
                    raise ValueError(f"Print STL was generated from a different source: {name}")
                if pr["sha256"] != hashlib.sha256(print_path.read_bytes()).hexdigest():
                    raise ValueError(f"Print STL differs from its recorded generation: {name}")
            pv,pt=read_stl(print_path)
            closed,_=_verify_closed(pv,pt)
            if closed["signed_volume_mm3"]<=0 or closed["positive_boundary_components"] != 1:
                raise ValueError(f"Print STL is not one connected positive solid: {name}")
            pr.update(closed)
            pr["source_model"]=name
            pr["source_stl_sha256"]=report["stl"]["sha256"]
            pr["sha256"]=hashlib.sha256(print_path.read_bytes()).hexdigest()
            if not args.check:
                write_json(report_path,pr)
            report["printable"]=pr
        reports.append(report)
        prepared.append(model)
        print(f"OK {name}: V={len(model['vertices'])}, defect error={report['max_defect_error']:.2e}, STL closed",flush=True)
    if not args.check:
        # A filtered run must not replace the full catalog with a partial one.
        if not args.model:
            write_catalog(args.output,prepared,reports)
        if args.preview:
            render_preview(prepared,args.output/"images"/"model_overview.png")
    print(f"{'Checked' if args.check else 'Generated'} {len(prepared)} models.",flush=True)


if __name__=="__main__":
    main()
