"""Build the offline viewer's model catalogue from the original polygon presentations."""

import json
from pathlib import Path


def export(root):
    models = []
    keys = ("name", "vertices", "faces", "orientable", "genus", "expected_defect",
            "construction", "parameters", "historical")
    for path in sorted((root / "models").glob("*.json")):
        if not path.name.startswith(("embedded_", "immersed_", "singular_")):
            continue
        model = json.loads(path.read_text(encoding="utf-8"))
        if not {"vertices", "faces", "genus"} <= model.keys():
            continue
        models.append({key: model[key] for key in keys if key in model})
    if not models:
        raise ValueError("No polygonal surface models found")
    body = ",\n".join(json.dumps(m, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
                      for m in models)
    target = root / "docs" / "viewer" / "models.js"
    target.write_text("// Generated by scripts/export_viewer_models.py from models/*.json.\n"
                      "const MODEL_LIBRARY = [\n" + body + "\n];\n", encoding="utf-8")


if __name__ == "__main__":
    export(Path(__file__).resolve().parents[1])
